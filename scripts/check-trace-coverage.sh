#!/usr/bin/env bash
# TASK-020 (FR-1105) gate: every use case emits a span named
# `<context>.<usecase>`.
#
# A use case is a file under a context's `src/application/` that declares an
# `fn execute(`, plus any non-`execute` entry point named in
# observability/use-case-entries.txt. Each required entry must be covered by
# a span (`#[instrument]` attribute, an `.instrument(...)` call, or an
# `info_span!`), and at least one span in the file must carry the context
# prefix in its name.
#
# The regenerated coverage matrix is compared against the committed copy —
# the matrix is the deliverable, and a stale one fails the gate exactly like
# a missing span. Regenerate it with `--write` and commit.
#
# Usage:
#   scripts/check-trace-coverage.sh            # gate
#   scripts/check-trace-coverage.sh --write    # regenerate observability/trace-coverage.md
#   scripts/check-trace-coverage.sh --self-test
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
matrix="$root/observability/trace-coverage.md"
registry="$root/observability/use-case-entries.txt"

VIOLATIONS=0
TOTAL_USE_CASES=0

# True when a registry entry names a function the file no longer declares —
# the registry has drifted and must be fixed before the gate can pass.
registry_stale() {
    local f="$1" name
    IFS=',' read -r -a names <<< "$2"
    for name in "${names[@]}"; do
        [[ -z "$name" ]] && continue
        grep -qE "fn ${name}\(" "$f" || return 0
    done
    return 1
}

# One matrix row for one file: `entries | spans | tenant refs | state`.
analyse_file() {
    local f="$1" ctx="$2" extra="$3" stale="$4"
    awk -v ctx="$ctx" -v extra="$extra" -v stale="$stale" '
        BEGIN {
            exec = 0; spans = 0; name_ok = 0; tenant = 0
            nextra = split(extra, ea, ",")
            if (nextra == 1 && ea[1] == "") nextra = 0
        }
        /fn execute\(/ { exec++ }
        /#\[(tracing::)?instrument/ { spans++ }
        /\.instrument\(/ { spans++ }
        /info_span!/ { spans++ }
        /tenant_id/ { tenant = 1 }
        {
            # A span name starting with this file’s context prefix, from
            # either `name = "ctx.…"` or the `info_span!("ctx.…", …)` form.
            if (match($0, "\"" ctx "\\.[a-z0-9_.]+\"")) name_ok = 1
        }
        END {
            required = exec + nextra
            state = "covered"
            if (required == 0) {
                state = "n/a"
            } else if (stale == 1) {
                state = "stale-registry"
            } else if (spans < required) {
                state = "missing span (" spans "/" required ")"
            } else if (!name_ok) {
                state = "span name lacks \"" ctx ".\" prefix"
            }
            printf "%d | %d | %s | %s", required, spans, (tenant ? "yes" : "no"), state
        }
    ' "$f"
}

# Emit the coverage matrix for a tree to stdout; collect violations in the
# VIOLATIONS global (never call this in a subshell).
scan_tree() {
    local tree="$1"
    local entries_file="$tree/observability/use-case-entries.txt"
    VIOLATIONS=0
    TOTAL_USE_CASES=0

    echo "# Trace coverage matrix — TASK-020 (FR-1105)"
    echo
    echo "Generated by \`scripts/check-trace-coverage.sh\` — do not edit by hand;"
    echo "regenerate with \`just trace-coverage-write\` and commit. The gate fails"
    echo "on any use case without a conforming span, and on a stale copy of this"
    echo "file."
    echo
    echo "Rules:"
    echo
    echo "- a *use case* is a file under \`crates/contexts/*/src/application/\`"
    echo "  declaring an \`fn execute(\`, plus the non-\`execute\` entry points"
    echo "  named in \`observability/use-case-entries.txt\`;"
    echo "- every entry is covered by a span, and at least one span in the file"
    echo "  is named \`<context>.<usecase>\`;"
    echo "- tenant-scoped use cases record \`tenant_id\` in the span fields —"
    echo "  the \`tenant refs\` column shows where that is expected, the gate"
    echo "  reviews it, it does not enforce it."
    echo
    echo "| context | use case | entries | spans | tenant refs | state |"
    echo "| --- | --- | --- | --- | --- | --- |"

    local search="$tree/crates/contexts"
    [[ -d "$search" ]] || return 0
    local f rel ctx extra stale_flag row state
    for f in $(find "$search" -path '*/src/application/*' -name '*.rs' ! -name 'mod.rs' | LC_ALL=C sort); do
        rel="${f#"$tree"/}"
        ctx="$(echo "$rel" | cut -d/ -f3)"
        extra=""
        if [[ -f "$entries_file" ]]; then
            extra="$(awk -v file="$rel" '$1 == file {printf "%s%s", sep, $2; sep = ","}' "$entries_file")"
        fi
        stale_flag=0
        if [[ -n "$extra" ]] && registry_stale "$f" "$extra"; then
            stale_flag=1
        fi
        row="$(analyse_file "$f" "$ctx" "$extra" "$stale_flag")"
        state="${row##*| }"
        printf '| %s | %s | %s\n' "$ctx" "${rel#crates/contexts/$ctx/src/application/}" "$row"
        case "$state" in
            covered | n/a) ;;
            *)
                echo "trace-coverage: $rel — $state" >&2
                VIOLATIONS=$((VIOLATIONS + 1))
                ;;
        esac
        if [[ "$state" != "n/a" ]]; then
            TOTAL_USE_CASES=$((TOTAL_USE_CASES + 1))
        fi
    done
}

write_matrix() {
    mkdir -p "$(dirname "$matrix")"
    scan_tree "$root" > "$matrix.tmp"
    mv "$matrix.tmp" "$matrix"
    echo "wrote $matrix"
    exit "$VIOLATIONS"
}

self_test() {
    local tree tmp
    tree="$(mktemp -d)"
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tree" "$tmp"' EXIT
    local app="$tree/crates/contexts/fake/src/application"
    mkdir -p "$app" "$tree/observability"

    cat > "$app/spanned.rs" <<'EOF'
pub struct Spanned;
impl Spanned {
    #[tracing::instrument(name = "fake.spanned", skip_all, fields(tenant_id = %t))]
    pub async fn execute(&self, t: u64) {}
}
EOF
    cat > "$app/gapped.rs" <<'EOF'
pub struct Gapped;
impl Gapped {
    pub async fn execute(&self) {}
}
EOF
    cat > "$app/unnamed.rs" <<'EOF'
pub struct Unnamed;
impl Unnamed {
    #[tracing::instrument(name = "other.usecase", skip_all)]
    pub async fn execute(&self) {}
}
EOF
    cat > "$app/dto.rs" <<'EOF'
pub struct Fields { pub name: String }
EOF
    cat > "$app/registry_entry.rs" <<'EOF'
pub struct Sweep;
impl Sweep {
    #[tracing::instrument(name = "fake.sweep_the_thing", skip_all)]
    pub async fn sweep_the_thing(&self) {}
}
EOF
    printf '%s %s\n' 'crates/contexts/fake/src/application/registry_entry.rs' 'sweep_the_thing' \
        > "$tree/observability/use-case-entries.txt"

    scan_tree "$tree" > "$tmp/out.md" 2> "$tmp/err.md"
    local out
    out="$(cat "$tmp/out.md" "$tmp/err.md")"

    if [[ "$VIOLATIONS" -ne 2 ]]; then
        echo "self-test failed: expected 2 violations (gapped, unnamed), got $VIOLATIONS" >&2
        exit 1
    fi
    grep -q 'gapped.rs — missing span (0/1)' <<<"$out" ||
        { echo "self-test failed: the spanless use case was not named" >&2; exit 1; }
    grep -q 'unnamed.rs — span name lacks "fake\." prefix' <<<"$out" ||
        { echo "self-test failed: a span without the context prefix was accepted" >&2; exit 1; }
    grep -q '| fake | dto.rs | 0 | 0 | no | n/a' <<<"$out" ||
        { echo "self-test failed: an entry-less file was not reported n/a" >&2; exit 1; }
    grep -q '| fake | registry_entry.rs | 1 | 1 | no | covered' <<<"$out" ||
        { echo "self-test failed: the registry entry was not required and covered" >&2; exit 1; }
    grep -q '| fake | spanned.rs | 1 | 1 | yes | covered' <<<"$out" ||
        { echo "self-test failed: the instrumented use case was not covered" >&2; exit 1; }

    # A registry entry naming a function the file does not declare is stale.
    printf '%s %s\n' 'crates/contexts/fake/src/application/registry_entry.rs' 'renamed_away' \
        > "$tree/observability/use-case-entries.txt"
    scan_tree "$tree" > "$tmp/out2.md" 2> "$tmp/err2.md"
    grep -q 'registry_entry.rs — stale-registry' "$tmp/err2.md" ||
        { echo "self-test failed: a stale registry entry was accepted" >&2; exit 1; }

    echo "trace-coverage self-test: OK (spanless, misnamed, stale-registry and n/a rows all behave; every violation names its file)"
    exit 0
}

case "${1:-}" in
    --self-test) self_test ;;
    --write) write_matrix ;;
    "") ;;
    *) echo "usage: $0 [--write|--self-test]" >&2; exit 2 ;;
esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
scan_tree "$root" > "$tmp/matrix.md"

if [[ "$VIOLATIONS" -gt 0 ]]; then
    echo "trace-coverage: FAILED — $VIOLATIONS use case(s) without a conforming span (of $TOTAL_USE_CASES)" >&2
    echo "trace-coverage: add the missing spans, then \`just trace-coverage-write\` and commit the matrix" >&2
else
    echo "trace-coverage: $TOTAL_USE_CASES use case(s) spanned"
fi

if [[ ! -f "$matrix" ]]; then
    echo "trace-coverage: $matrix is not committed yet — run \`just trace-coverage-write\`" >&2
    exit 1
fi
if ! diff -u "$matrix" "$tmp/matrix.md" > "$tmp/stale.diff"; then
    echo "trace-coverage: the committed matrix is stale —" >&2
    cat "$tmp/stale.diff" >&2
    echo "trace-coverage: run \`just trace-coverage-write\` and commit" >&2
    exit 1
fi

exit "$VIOLATIONS"
