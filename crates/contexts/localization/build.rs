//! Build script: embeds the static message catalogs and derives the
//! compile-time key table the `t!` macro checks against.
//!
//! Layout: `catalogs/{locale}/{domain}.json` — each file a flat
//! `{ "key": "ICU-style pattern" }` map. `en` is the source locale: its key
//! set is the contract every other locale must match (enforced by
//! `cargo run -p sanvi-cli -- i18n check` in CI).

use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=catalogs");

    let catalogs_dir = Path::new("catalogs");
    let mut files: Vec<(String, String, String)> = Vec::new();
    let mut locales: Vec<String> = Vec::new();

    for locale_entry in fs::read_dir(catalogs_dir).expect("catalogs directory must exist") {
        let locale_dir = locale_entry.expect("catalogs entry").path();
        if !locale_dir.is_dir() {
            continue;
        }
        let locale = locale_dir
            .file_name()
            .expect("locale dir name")
            .to_str()
            .expect("locale name is utf-8")
            .to_string();
        locales.push(locale.clone());

        let mut domain_files: Vec<_> = fs::read_dir(&locale_dir)
            .expect("locale directory must be readable")
            .map(|entry| entry.expect("catalog entry").path())
            .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
            .collect();
        domain_files.sort();

        for path in domain_files {
            let domain = path
                .file_stem()
                .expect("catalog file stem")
                .to_str()
                .expect("catalog name is utf-8")
                .to_string();
            files.push((
                locale.clone(),
                domain,
                path.canonicalize()
                    .expect("catalog path canonicalizes")
                    .to_string_lossy()
                    .to_string(),
            ));
        }
    }

    locales.sort();
    files.sort();

    // The `en` catalog is the source of truth for the key table.
    let mut keys: Vec<String> = Vec::new();
    for (locale, _domain, path) in &files {
        if locale != "en" {
            continue;
        }
        let content = fs::read_to_string(path).expect("catalog file must be readable");
        let map: serde_json::Map<String, serde_json::Value> = serde_json::from_str(&content)
            .unwrap_or_else(|err| {
                panic!("catalog {path} is not valid JSON: {err}");
            });
        keys.extend(map.keys().cloned());
    }
    keys.sort();
    keys.dedup();

    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n\n");

    out.push_str("/// Every embedded catalog file: (locale, domain, json content).\n");
    out.push_str("pub static CATALOG_FILES: &[(&str, &str, &str)] = &[\n");
    for (locale, domain, path) in &files {
        out.push_str(&format!(
            "    (\"{locale}\", \"{domain}\", include_str!({path:?})),\n"
        ));
    }
    out.push_str("];\n\n");

    out.push_str("/// The locales that ship with the binary, in preferred order.\n");
    out.push_str("pub static SHIPPED_LOCALES: &[&str] = &[\n");
    for locale in &locales {
        out.push_str(&format!("    \"{locale}\",\n"));
    }
    out.push_str("];\n\n");

    out.push_str("/// The complete key set of the source (`en`) catalog, sorted.\n");
    out.push_str("pub static KNOWN_KEYS: &[&str] = &[\n");
    for key in &keys {
        out.push_str(&format!("    \"{key}\",\n"));
    }
    out.push_str("];\n\n");

    out.push_str(
        "/// Compile-time key existence check, consumed by the `t!` macro.\n\
         pub const fn is_known_key(key: &str) -> bool {\n\
         \x20   let bytes = key.as_bytes();\n\
         \x20   let mut i = 0;\n\
         \x20   while i < KNOWN_KEYS.len() {\n\
         \x20       let candidate = KNOWN_KEYS[i].as_bytes();\n\
         \x20       if bytes.len() == candidate.len() {\n\
         \x20           let mut j = 0;\n\
         \x20           let mut equal = true;\n\
         \x20           while j < bytes.len() {\n\
         \x20               if bytes[j] != candidate[j] {\n\
         \x20                   equal = false;\n\
         \x20                   break;\n\
         \x20               }\n\
         \x20               j += 1;\n\
         \x20           }\n\
         \x20           if equal {\n\
         \x20               return true;\n\
         \x20           }\n\
         \x20       }\n\
         \x20       i += 1;\n\
         \x20   }\n\
         \x20   false\n\
         }\n",
    );

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR is set");
    fs::write(Path::new(&out_dir).join("generated_catalogs.rs"), out)
        .expect("generated catalog file writes");
}
